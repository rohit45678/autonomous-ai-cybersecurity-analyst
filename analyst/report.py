"""Incident report generation: one Markdown report per incident cluster."""

from __future__ import annotations

from pathlib import Path

from .investigation import IncidentCluster
from .models import TriageResult

# MITRE ATT&CK mapping per alert type (technique id, name).
ATTACK_MAPPING = {
    "brute_force": ("T1110.001", "Brute Force: Password Guessing"),
    "auth_success_after_failures": ("T1078", "Valid Accounts"),
    "privilege_escalation": ("T1098", "Account Manipulation"),
    "suspicious_process": ("T1059.001", "Command and Scripting Interpreter: PowerShell"),
    "impossible_travel": ("T1078", "Valid Accounts"),
    "vpn_login": ("T1133", "External Remote Services"),
    "data_exfiltration": ("T1048", "Exfiltration Over Alternative Protocol"),
    "dns_anomaly": ("T1071.004", "Application Layer Protocol: DNS"),
    "malware_detected": ("T1204.002", "User Execution: Malicious File"),
    "c2_beacon": ("T1071.001", "Application Layer Protocol: Web Protocols"),
    "persistence_startup": ("T1547.001", "Boot or Logon Autostart Execution: Registry Run Keys / Startup Folder"),
    "port_scan": ("T1046", "Network Service Discovery"),
    "failed_logon": ("T1110", "Brute Force"),
}

RECOMMENDED_ACTIONS = {
    "brute_force": "Block the source IP at the perimeter and force a password reset for the targeted account.",
    "auth_success_after_failures": "Treat the account as compromised: revoke active sessions and review all activity since the successful logon.",
    "privilege_escalation": "Remove the unauthorized group membership and audit who approved the change.",
    "suspicious_process": "Isolate the host and capture the decoded script/command line for forensic review.",
    "impossible_travel": "Suspend the account pending identity verification with the user and their manager.",
    "vpn_login": "Confirm the logon with the user out-of-band; if unrecognized, revoke VPN certificates.",
    "data_exfiltration": "Preserve network flow records, identify the data staged for transfer, and engage Legal/Privacy for exposure assessment.",
    "dns_anomaly": "Block the domain at the resolver and hunt for the same domain across all endpoints.",
    "malware_detected": "Quarantine the file and host, and hunt the hash across the fleet.",
    "c2_beacon": "Block the C2 destination at proxy and firewall; reimage the host if execution is confirmed.",
    "persistence_startup": "Remove the autostart artifact and review the host for additional persistence mechanisms.",
    "port_scan": "Verify the scan is an authorized assessment; otherwise identify and contain the source host.",
}

GENERAL_ACTIONS = [
    "Reset credentials and revoke tokens/sessions for every affected account.",
    "Open a ticket in the incident tracker and assign an incident commander.",
    "Retain logs for all affected hosts and accounts for at least 90 days.",
]


def _evidence_lines(result: TriageResult) -> list[str]:
    alert = result.alert
    enrichment = result.enrichment
    details = ", ".join(f"{k}={v}" for k, v in alert.details.items()) or "n/a"
    lines = [
        f"- **{alert.id}** ({alert.alert_type}) at {alert.timestamp.isoformat()} — "
        f"score {result.score}, {result.severity}, disposition {result.disposition}",
        f"  - user={alert.user or 'n/a'}, host={alert.host or 'n/a'}, "
        f"src={alert.src_ip or 'n/a'}, dst={alert.dst_ip or 'n/a'}",
        f"  - details: {details}",
        f"  - context: asset criticality={enrichment.asset_criticality}, "
        f"user department={enrichment.user_department or 'n/a'}, "
        f"admin={enrichment.user_is_admin}, sensitive-data access={enrichment.user_sensitive_data_access}",
        "  - scoring signals: " + "; ".join(result.signals),
    ]
    return lines


def render_report(cluster: IncidentCluster, generated_by: str = "autonomous-ai-cybersecurity-analyst") -> str:
    lines: list[str] = []
    lines.append(f"# Incident Report {cluster.id}")
    lines.append("")
    lines.append(f"- **Severity:** {cluster.severity} (max alert score {cluster.max_score})")
    lines.append(f"- **Window:** {cluster.start.isoformat()} → {cluster.end.isoformat()}")
    lines.append(f"- **Affected users:** {', '.join(cluster.users) or 'n/a'}")
    lines.append(f"- **Affected hosts:** {', '.join(cluster.hosts) or 'n/a'}")
    lines.append(f"- **Alert types:** {', '.join(cluster.alert_types)}")
    lines.append(f"- **Generated by:** {generated_by}")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append(
        f"{len(cluster.members)} correlated alert(s) were grouped into this incident "
        f"between {cluster.start.isoformat()} and {cluster.end.isoformat()}. "
        f"The highest-scoring alert reached {cluster.max_score}/100 and the incident "
        f"severity is {cluster.severity}. Immediate containment is recommended before "
        "the investigation is closed."
    )
    lines.append("")
    lines.append("## Timeline")
    lines.append("")
    lines.append("| Time (UTC) | Alert | Type | User | Host | Score | Disposition |")
    lines.append("|---|---|---|---|---|---|---|")
    for member in cluster.members:
        alert = member.alert
        lines.append(
            f"| {alert.timestamp.strftime('%Y-%m-%d %H:%M:%S')} | {alert.id} | {alert.alert_type} "
            f"| {alert.user or '-'} | {alert.host or '-'} | {member.score} | {member.disposition} |"
        )
    lines.append("")
    lines.append("## Evidence")
    lines.append("")
    for member in cluster.members:
        lines.extend(_evidence_lines(member))
    lines.append("")
    lines.append("## MITRE ATT&CK Mapping")
    lines.append("")
    seen: set[str] = set()
    for member in cluster.members:
        mapping = ATTACK_MAPPING.get(member.alert.alert_type)
        if mapping and mapping[0] not in seen:
            seen.add(mapping[0])
            lines.append(f"- **{mapping[0]}** — {mapping[1]} (from `{member.alert.alert_type}`)")
    if not seen:
        lines.append("- No ATT&CK mapping available for these alert types.")
    lines.append("")
    lines.append("## Recommended Actions")
    lines.append("")
    actions: list[str] = []
    for member in cluster.members:
        action = RECOMMENDED_ACTIONS.get(member.alert.alert_type)
        if action and action not in actions:
            actions.append(action)
    for action in actions + GENERAL_ACTIONS:
        lines.append(f"- {action}")
    lines.append("")
    return "\n".join(lines)


def write_reports(clusters: list[IncidentCluster], out_dir: str | Path) -> list[Path]:
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for cluster in clusters:
        target = out_path / f"{cluster.id.lower()}-report.md"
        target.write_text(render_report(cluster), encoding="utf-8")
        written.append(target)
    return written
